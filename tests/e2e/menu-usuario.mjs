import { chromium } from "playwright";
import { entrar } from "./auth-helper.mjs";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome", args: ["--no-proxy-server"] });
const page = await (await browser.newContext({ locale: "pt-BR", viewport: { width: 1440, height: 900 } })).newPage();
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
await entrar(page, "breno@implantta.com.br"); await page.waitForURL(/painel/);
assert.equal(await page.locator("aside").getByText("Sair").count(), 0, "sem Sair no menu lateral");
assert.equal(await page.locator("aside a[href='/meu-perfil']").count(), 0, "sem perfil no menu lateral");
await page.screenshot({ path: "shots3/menu-1.png" });
await page.locator("header button[aria-haspopup=menu]").hover();
await page.getByRole("menuitem", { name: "Sair" }).waitFor();
await page.screenshot({ path: "shots3/menu-2-hover.png", clip: { x: 900, y: 0, width: 540, height: 200 } });
await page.mouse.move(400, 500); await page.waitForTimeout(500);
assert.equal(await page.getByRole("menu").count(), 0, "fecha ao sair com o mouse");
await page.locator("header button[aria-haspopup=menu]").click();
await page.getByRole("menuitem", { name: "Sair" }).waitFor();
await page.keyboard.press("Escape");
assert.equal(await page.getByRole("menu").count(), 0, "Esc fecha");
await page.mouse.move(400, 500);
await page.locator("header button[aria-haspopup=menu]").hover();
await page.getByRole("menuitem", { name: "Meu perfil" }).click();
await page.waitForURL(/meu-perfil/);
// celular: toque abre
const m = await (await browser.newContext({ locale: "pt-BR", viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, storageState: await page.context().storageState() })).newPage();
await m.goto("http://localhost:3000/painel");
await m.locator("header button[aria-haspopup=menu]").tap();
await m.getByRole("menuitem", { name: "Sair" }).waitFor();
await m.screenshot({ path: "shots3/menu-3-celular.png" });
await m.getByRole("menuitem", { name: "Sair" }).tap();
await m.waitForURL(/login/);
console.log("menu: ok");
process.exit(0);
