import { chromium } from "playwright";
const SK = process.env.SERVICE_KEY;
const tr = await (await fetch("http://localhost:54321/rest/v1/tracks?select=id,name&name=eq.Onboarding%20Comercial", { headers: { apikey: SK, Authorization: `Bearer ${SK}` } })).json();
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome", args: ["--no-proxy-server"] });
const page = await (await browser.newContext({ locale: "pt-BR", viewport: { width: 1440, height: 900 } })).newPage();
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
page.on("console", (m) => m.type() === "error" && console.log("[console]", m.text().slice(0, 200)));
await page.goto("http://localhost:3000/login");
await page.fill("#email", "breno@implantta.com.br"); await page.fill("#password", "SenhaForte!2026");
await page.click("form button[type=submit]"); await page.waitForURL(/painel/);
await page.goto("http://localhost:3000/trilhas");
await page.locator(`a[href="/trilhas/${tr[0].id}"]`).first().click();
await page.getByRole("dialog").getByRole("tab", { name: /Estrutura/ }).waitFor();
await page.waitForTimeout(600);
await page.screenshot({ path: "shots/tabs-1.png" });
await page.getByRole("button", { name: "Cadastrar conteúdo neste módulo" }).first().click();
await page.waitForTimeout(400);
await page.screenshot({ path: "shots/tabs-2.png" });
await page.getByRole("tab", { name: "Novo módulo" }).click(); await page.waitForTimeout(300);
await page.screenshot({ path: "shots/tabs-3.png" });
await page.getByRole("tab", { name: "Dados e público" }).click(); await page.waitForTimeout(300);
await page.screenshot({ path: "shots/tabs-4.png" });
const D = page.getByRole("dialog", { name: "Editar trilha" });
await D.getByRole("tab", { name: "Novo módulo" }).click();
await page.fill("#new-mod-title", "Módulo pela janela B");
await D.getByRole("button", { name: "Criar módulo" }).click();
await page.getByText('Módulo "Módulo pela janela B" criado.').waitFor();
await D.getByRole("tab", { name: /Estrutura/, selected: true }).waitFor();
await D.locator("p.font-semibold", { hasText: "Módulo pela janela B" }).waitFor();
console.log("módulo criado na janela: ok");
await D.getByRole("button", { name: "Cadastrar conteúdo neste módulo" }).last().click();
await page.fill("#title", "Conteúdo pela janela");
await D.locator("label", { hasText: /^Texto$/ }).click();
await page.fill("#body", "Feito sem sair da trilha.");
await D.getByRole("button", { name: "Criar e publicar" }).click();
await page.getByText(/publicado e incluído no módulo/).waitFor();
await D.getByRole("tab", { name: /Estrutura/, selected: true }).waitFor();
await D.locator("a", { hasText: "Conteúdo pela janela" }).waitFor();
console.log("conteúdo criado na janela: ok", page.url());
await page.waitForTimeout(2800);
await D.locator("a", { hasText: "Conteúdo pela janela" }).scrollIntoViewIfNeeded();
await page.screenshot({ path: "shots/tabs-5.png" });
process.exit(0);
